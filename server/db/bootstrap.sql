\set ON_ERROR_STOP ON_ERROR_STOP
\getenv owner_password SCREEN_TRACK_OWNER_PASSWORD
\getenv app_password SCREEN_TRACK_APP_PASSWORD
SELECT current_database() AS app_db \gset

CREATE ROLE screen_track_owner LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS PASSWORD :'owner_password';
CREATE ROLE screen_track_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS PASSWORD : 'app_password';

REVOKE CONNECT, TEMPROARY ON DATABASE :"app_db" FROM PUBLIC;
GRANT CONNECT, CREATE ON DATABASE :"app_db" TO screen_track_owner;
GRANT CONNECT ON DATABASE :"app_db" TO screen_track_app;
REVOKE CREATE ON SCHEMA public from PUBLIC;